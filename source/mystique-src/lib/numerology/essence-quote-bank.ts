export function formatQuotes(raw: number, reduced: number, name: string | undefined, quotes: EssenceQuotes | null): string {
  if (!quotes) return `${raw}/${reduced}${name ? ` — ${name}` : ""}`;
  return `${raw}/${reduced} — ${name ?? quotes.symbol.slice(0, 60)}`;
}
