/**
 * Builds mystique-src/lib/numerology/personal-year-precedents.ts — a compact
 * index of the 429 dated life events in the personal-year history banks.
 *
 *   cd source && node scripts/run-ts.mjs scripts/build-precedent-index.ts
 *
 * The banks themselves (~490 KB) are not imported by the app. This index keeps
 * only what the woven synthesis needs (~90 KB) and recomputes every Direct /
 * Classic number from the person's birth date, so a typo in a bank can't reach
 * the UI. Cases without a verifiable birth date are left out.
 */
import fs from 'node:fs';
import path from 'node:path';
import { famousBirthdays } from '@/lib/famous-birthdays';
import { HISTORICAL_BIRTH_DATES, normaliseHistoricalPersonName } from '@/lib/numerology/personal-year-history-birthdates';
import { HISTORICAL_CASES_EXPANSION_200 } from '@/lib/numerology/personal-year-history-expanded';
import { HISTORICAL_CASES_EXPANSION_300_EXTRA } from '@/lib/numerology/personal-year-history-expanded-2';
import { HISTORICAL_CASES_EXPANSION_300_MORE } from '@/lib/numerology/personal-year-history-expanded-3';
import { HISTORICAL_CASES_EXPANSION_FINAL } from '@/lib/numerology/personal-year-history-expanded-4';

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.resolve(here, '../mystique-src/lib/numerology/personal-year-precedents.ts');

const digitSum = (n: number) => String(Math.abs(n)).split('').reduce((a, c) => a + +c, 0);
const single = (n: number) => { let v = Math.abs(n); while (v > 9) v = digitSum(v); return v; };
const normName = (n: string) => n.replace(/\s*†/g, '').replace(/\s*\([^)]*\)\s*$/, '').trim();

const dob = new Map<string, { day: number; month: number; year: number }>();
for (const p of famousBirthdays) if (!p.tags.includes('Entity')) dob.set(normaliseHistoricalPersonName(normName(p.name)), p);
for (const [k, b] of Object.entries(HISTORICAL_BIRTH_DATES)) dob.set(k, b);

// First sentence, lower-cased start, no trailing full stop: reads after "on the surface, ".
function what(text: string): string {
  let s = (text || '').replace(/\s+/g, ' ').trim();
  const cut = s.search(/(?<=[a-z0-9”’)])\.\s/);
  if (cut > 40) s = s.slice(0, cut);
  s = s.replace(/[.\s]+$/, '');
  if (s.length > 170) s = s.slice(0, s.lastIndexOf(' ', 165)) + '…';
  return s;
}
// Lower-case the opening word only when it's a verb or an article/pronoun —
// never a name, company or film title ("SpaceX", "Titanic", "Good Will Hunting").
const VERBS = new Set(('won was were became led lost began left kept sent swept withdrew came ran hit set bit read made broke struck shot sold died ' +
  'shared scored announced resigned returned transferred signed continued completed testified stepped helped faced headlined took gave ' +
  'went got had held built wrote won’t rose fell drew beat met paid fought threw split spent stood told underwent oversaw overtook ' +
  'the a an her his their its after in at with for as publicly narrowly').split(' '));
const sentenceCase = (s: string) => {
  const w = s.split(' ')[0];
  return /^[A-Z][a-z-]+$/.test(w) && (VERBS.has(w.toLowerCase()) || /^[A-Z][a-z-]+ed$/.test(w)) ? s[0].toLowerCase() + s.slice(1) : s;
};

const cases = [...HISTORICAL_CASES_EXPANSION_200, ...HISTORICAL_CASES_EXPANSION_300_EXTRA, ...HISTORICAL_CASES_EXPANSION_300_MORE, ...HISTORICAL_CASES_EXPANSION_FINAL];
const rows: string[] = [];
let skipped = 0;
for (const c of cases) {
  const b = dob.get(normaliseHistoricalPersonName(c.person));
  if (!b) { skipped++; continue; }
  const d = b.day + b.month + digitSum(c.year);
  const k = digitSum(b.day) + digitSum(b.month) + single(c.year);
  const row = [c.person, c.year, b.day, b.month, d, k, c.outcome, sentenceCase(what(c.eventDetails || c.narrative))];
  rows.push('  ' + JSON.stringify(row));
}

fs.writeFileSync(out, `// AUTO-GENERATED by scripts/build-precedent-index.ts — do not edit by hand.
// Source: personal-year-history-expanded*.ts (${cases.length} cases, ${skipped} without a verifiable birth date).
// Row: [person, eventYear, birthDay, birthMonth, directRaw, classicRaw, outcome, what happened]

export type PrecedentOutcome = 'triumph' | 'legacy' | 'mixed' | 'transition' | 'loss';
export interface Precedent {
  person: string; year: number; birthDay: number; birthMonth: number;
  directRaw: number; classicRaw: number; outcome: PrecedentOutcome; what: string;
}

const ROWS: Array<[string, number, number, number, number, number, string, string]> = [
${rows.join(',\n')}
];

export const PERSONAL_YEAR_PRECEDENTS: Precedent[] = ROWS.map(([person, year, birthDay, birthMonth, directRaw, classicRaw, outcome, what]) => ({
  person, year, birthDay, birthMonth, directRaw, classicRaw, outcome: outcome as PrecedentOutcome, what,
}));
`);
console.log(`wrote ${rows.length} precedents (${skipped} skipped) → ${path.relative(process.cwd(), out)} (${fs.statSync(out).size} bytes)`);
